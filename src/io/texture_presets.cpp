std::span<const TexturePreset> texturePresets() { return presets; }

QByteArray texturePresetBytes(const TexturePreset &preset) {
    if (preset.resource.empty())
        return proceduralTextureJpeg(preset.generated);
    QFile file(QStringLiteral(":/sketchyup/textures/") +
               QString::fromLatin1(preset.resource.data(), qsizetype(preset.resource.size())));
    if (!file.open(QIODevice::ReadOnly))
        throw std::runtime_error("The texture file is missing from this build");
    return file.readAll();
}

