// Rewrites the manifest through `edit` and rebuilds the envelope header. The payload region is
// unchanged, so every record hash still matches its bytes.
inline QByteArray withManifest(const QByteArray &file,
                               const std::function<void(QJsonObject &)> &edit) {
    const auto manifestSize = qFromLittleEndian<quint32>(file.constData() + 8);
    auto manifest = QJsonDocument::fromJson(file.mid(24, manifestSize)).object();
    edit(manifest);
    const auto text = QJsonDocument(manifest).toJson(QJsonDocument::Compact);
    QByteArray result = file.left(24);
    qToLittleEndian<quint32>(quint32(text.size()), result.data() + 8);
    return result + text + file.mid(24 + manifestSize);
}
// Changes the byte at `payloadOffset` inside the payload region (not the envelope).
inline QByteArray flipPayloadByte(QByteArray file, qsizetype payloadOffset) {
    const auto manifestSize = qFromLittleEndian<quint32>(file.constData() + 8);
    file[24 + manifestSize + payloadOffset] = char(file[24 + manifestSize + payloadOffset] ^ 0x5a);
    return file;
}
// R100.d: a textured material and an edge-textured style that share one asset, and a block. The
// component has a fixed identity, so the bytes are reproducible and the committed file matches.
